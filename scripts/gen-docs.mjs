// Writes docs/reference/{cli,config}.md, docs/public/config.schema.json and the docs' screens from the CLI's source, no build needed.
import { execFileSync } from 'node:child_process'
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { stripVTControlCharacters } from 'node:util'

const HOME = '/HOME'
const header = (description) =>
  `---\ndescription: ${description}\n---\n\n<!-- Generated by \`pnpm docs:gen\` from the built CLI. Do not edit. -->\n`
const schemaUrl = 'https://andreaprovenzale.github.io/awaywork/config.schema.json'

const fromSource = (script, args = [], env = {}) =>
  execFileSync(
    'node',
    [
      '--experimental-transform-types',
      '--disable-warning=ExperimentalWarning',
      '--import',
      './scripts/ts-resolve.mjs',
      script,
      ...args,
    ],
    {
      encoding: 'utf8',
      env: { ...process.env, HOME, COLUMNS: '80', ...env },
    },
  )
    .replaceAll(HOME, '~')
    .trimEnd()

const cli = (...args) => fromSource('src/cli/index.ts', args)

function commands(path) {
  const help = cli(...path, '--help')
  const names = [...(help.split('\nCommands:\n')[1] ?? '').matchAll(/^ {2}(\S+)/gm)]
    .map((m) => m[1])
    .filter((name) => name !== 'help')
  return [{ path, help }, ...names.flatMap((name) => commands([...path, name]))]
}

function cliDoc() {
  const sections = commands([]).map(
    ({ path, help }) => `## ${['awaywork', ...path].join(' ')}\n\n\`\`\`text\n${help}\n\`\`\``,
  )
  return `${header('Every awaywork command and option, from its --help.')}
# CLI reference

Every command's \`--help\`. The global \`--config\` option applies to all of them.

${sections.join('\n\n')}
`
}

// Vue compiles the page: a bare <name> outside a code span would open an element, and {{ }} interpolate.
const literalTags = (s) => {
  if (s.includes('{{')) throw new Error(`Vue would interpolate the {{ in: ${s}`)
  return s.replace(/(`+).*?\1|\\?</gs, (m) => (m === '<' ? '\\<' : m))
}

const cell = (s) => literalTags(String(s)).replaceAll('|', '\\|').replaceAll('\n', ' ')

let defs = {}

/** A $ref replaced by its definition, keeping the description and default set beside it. */
const resolve = ({ $ref, ...rest }) => ($ref ? { ...defs[$ref.split('/').pop()], ...rest } : rest)

function typeOf(s) {
  if (s.$ref) return typeOf(resolve(s))
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(' \\| ')
  if (s.anyOf) return [...new Set(variants(s))].join(' \\| ')
  if (s.pattern?.endsWith('%$')) return 'percent'
  if (s.pattern?.includes('[0-5]\\d$')) return 'time'
  if (s.type === 'array') {
    const item = typeOf(s.items)
    return item.includes('|') ? `(${item})[]` : `${item}[]`
  }
  if (s.type === 'object') return s.properties ? 'object' : 'map'
  return [s.type].flat().join(' \\| ')
}

/** A union's types, with nested unions flattened so each type shows once. */
const variants = (s) => (s.anyOf ? s.anyOf.flatMap(variants) : [typeOf(s)])

/** Every object schema with properties, keyed by its YAML path, in document order. */
function objects(s, path, out, open = []) {
  if (s.$ref) {
    // A recursive schema, e.g. where inside any, is documented once.
    if (open.includes(s.$ref)) return out
    return objects(resolve(s), path, out, [...open, s.$ref])
  }
  if (s.properties) {
    out.push({ path, schema: s })
    for (const [key, sub] of Object.entries(s.properties))
      objects(sub, path ? `${path}.${key}` : key, out, open)
  }
  if (s.items) objects(s.items, `${path}[]`, out, open)
  if (s.additionalProperties && typeof s.additionalProperties === 'object')
    objects(s.additionalProperties, `${path}.<key>`, out, open)
  for (const variant of s.anyOf ?? []) objects(variant, path, out, open)
  return out
}

function configDoc(schema) {
  defs = schema.$defs
  const seen = new Map()
  const shapes = new Map()
  const sections = objects(schema, '', []).map(({ path, schema: s }) => {
    const key = JSON.stringify(s)
    // A second shape at one path, e.g. a loop where a step goes, is named by its first key.
    if (!shapes.has(path)) shapes.set(path, key)
    const variant = shapes.get(path) === key ? '' : ` (${Object.keys(s.properties)[0]})`
    const name = path ? `\`${path}\`${variant}` : 'Top level'
    const title = `## ${name}`
    if (seen.has(key)) return `${title}\n\nSame keys as ${seen.get(key)}.`
    seen.set(key, name)
    const required = new Set(s.required ?? [])
    const rows = Object.entries(s.properties).map(([name, p]) => {
      const def = p.default === undefined ? '' : `\`${JSON.stringify(p.default)}\``
      const req = required.has(name) && p.default === undefined ? ' (required)' : ''
      return `| \`${name}\`${req} | ${typeOf(p)} | ${cell(def)} | ${cell(p.description ?? '')} |`
    })
    const intro = s.description ? `${literalTags(s.description)}.\n\n` : ''
    return `${title}\n\n${intro}| Key | Type | Default | Description |\n|---|---|---|---|\n${rows.join('\n')}`
  })
  // A union can reach one object twice at a path, e.g. a step alone or in a list.
  const unique = [...new Set(sections)]
  return `${header('Every config key with its type, default and meaning, from the JSON Schema.')}
# Config reference

Generated from the JSON Schema that \`awaywork config schema\` prints,
also published at [\`config.schema.json\`](${schemaUrl}). For autocompletion
and hover docs in editors with the YAML language server, start the config
with:

\`\`\`yaml
# yaml-language-server: $schema=${schemaUrl}
\`\`\`

\`<key>\` stands for a map key you choose, \`[]\` for a list entry.
\`awaywork doctor\` validates what the schema cannot, such as
\`where\` keys and skill names.

${unique.join('\n\n')}
`
}

const schema = cli('config', 'schema')
mkdirSync('docs/reference', { recursive: true })
mkdirSync('docs/public', { recursive: true })
writeFileSync('docs/public/config.schema.json', `${schema}\n`)
writeFileSync('docs/reference/cli.md', cliDoc())
writeFileSync('docs/reference/config.md', configDoc(JSON.parse(schema)))

const marker = '<!-- Generated by `pnpm docs:gen` from scripts/screens.ts. Do not edit. -->'
const escaped = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

/** Each screen's colors for the site, and its plain text into every ```<lang> <name> block that shows it. */
function writeScreens() {
  const screens = JSON.parse(fromSource('scripts/screens.ts', [], { FORCE_COLOR: '3', TZ: 'UTC' }))
  rmSync('docs/.vitepress/screens', { recursive: true, force: true })
  mkdirSync('docs/.vitepress/screens')
  for (const [name, colored] of Object.entries(screens))
    writeFileSync(`docs/.vitepress/screens/${name}.ansi`, `${colored}\n`)
  const pages = readdirSync('docs', { recursive: true })
    .filter((f) => f.endsWith('.md') && !f.startsWith('.vitepress'))
    .map((f) => `docs/${f}`)
  // A block may sit indented in a list, and use four backticks to hold a fence of its own.
  const block = new RegExp(
    `^(?: *${escaped(marker)}\\n\\n)?( *)(\`{3,})(\\w+) (\\S+)\\n[\\s\\S]*?^\\1\\2$`,
    'gm',
  )
  for (const path of ['README.md', ...pages]) {
    const text = readFileSync(path, 'utf8')
    const shown = text.replace(block, (_block, indent, fence, lang, name) => {
      if (!(name in screens)) throw new Error(`${path}: no screen "${name}" in scripts/screens.ts`)
      const lines = stripVTControlCharacters(screens[name]).split('\n')
      if (lines.some((line) => line.startsWith(fence)))
        throw new Error(`${path}: screen "${name}" holds a ${fence} fence; use a longer one`)
      return [marker, '', `${fence}${lang} ${name}`, ...lines, fence]
        .map((line) => (line ? indent + line : line))
        .join('\n')
    })
    if (shown !== text) writeFileSync(path, shown)
  }
}

writeScreens()
